async page => {
  await page.setViewportSize({width:960,height:840})
  const input=page.getByRole('searchbox',{name:'搜索私聊联系人'})
  await input.fill('目录同事')
  const found=page.getByRole('checkbox',{name:'目录同事 directory_demo_1 · 测试部门',exact:true})
  await found.waitFor();await found.check()
  await page.getByRole('button',{name:'移除 目录同事',exact:true}).waitFor()
  await input.fill('另一人')
  await page.getByRole('checkbox',{name:'另一人 directory_demo_1 · 测试部门',exact:true}).waitFor()
  if(!await page.getByRole('button',{name:'移除 目录同事',exact:true}).isVisible())throw Error('Selection lost on query change')
  await input.fill('分页')
  await page.getByRole('button',{name:'加载更多人员',exact:true}).click()
  await page.getByRole('checkbox',{name:'分页 directory_demo_2 · 测试部门',exact:true}).waitFor()
  await input.fill('无匹配')
  await page.getByText('咚咚通讯录未找到匹配人员，请换个姓名或账号。').waitFor()
  await page.evaluate(()=>document.body.dataset.searchFail='true')
  await input.fill('失败查询')
  await page.getByRole('button',{name:'重试搜索',exact:true}).waitFor()
  await page.evaluate(()=>delete document.body.dataset.searchFail)
  await page.getByRole('button',{name:'重试搜索',exact:true}).click()
  await page.getByRole('checkbox',{name:/失败查询/}).waitFor()
  await input.fill('慢查询')
  await input.press('Enter')
  await input.fill('新查询')
  await page.getByRole('checkbox',{name:/新查询/}).waitFor()
  await page.waitForTimeout(1400)
  if(await page.getByRole('checkbox',{name:/过时结果/}).count())throw Error('Old search overwrote new query')
  await page.locator('.auto-reply-settings').scrollIntoViewIfNeeded()
  await page.screenshot({path:'output/playwright/directory-search.png'})
  await page.getByRole('button',{name:'开启 1 小时',exact:true}).click()
  await page.getByRole('button',{name:'关闭自动回复',exact:true}).waitFor()
  const config=await page.evaluate(()=>JSON.parse(document.body.dataset.replyConfigured))
  if(config.contacts.join()!=='directory-目录同事-1')throw Error('Wrong selected remote user')
  await page.getByRole('button',{name:'关闭自动回复',exact:true}).click()
  await page.evaluate(()=>{
    const a=window.__messageFixtureState().autoReply
    window.__setAutoReply({...a,epoch:'switched',enabled:false,contacts:[],logs:[]})
  })
  await page.waitForFunction(()=>document.querySelector('.reply-search').value==='')
  if(await page.getByRole('button',{name:'移除 目录同事',exact:true}).count())throw Error('Old account selection retained')
  if(!await page.getByRole('button',{name:'开启 1 小时',exact:true}).isDisabled())throw Error('Switch left enable possible')
  console.log('PASS: remote search, persistent selection, pagination, empty/error/retry, stale response, remote selection config, source reset. No real message sent.')
}
